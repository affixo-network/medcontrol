'use strict';
const {test,expect}=require('@playwright/test');
test('course completes on final taken slot, archives exactly seven days later, survives encrypted offline restart',async({browser})=>{
 const context=await browser.newContext({serviceWorkers:'allow',timezoneId:'Asia/Yerevan'});
 const page=await context.newPage();
 await page.goto('http://127.0.0.1:8765/tests/modular3-offline-access.html');
 await page.evaluate(async()=>{await navigator.serviceWorker.register('/tests/modular3-offline-sw.js',{scope:'/tests/'});await navigator.serviceWorker.ready;});
 await page.reload();await context.setOffline(true);await page.reload();
 await page.locator('#passphrase').fill('Archive-Synthetic-Secret-2026');
 await page.getByRole('button',{name:'Unlock offline'}).click();
 await expect(page.locator('#sections')).toBeVisible();
 const result=await page.evaluate(async()=>{
  const bridge=window.MedControlOfflineEncryptedBridge,engine=window.MedControlOfflineCourseEngine;
  const state=bridge.read(),day=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Yerevan'});
  const med=engine.create(state,'Archive Test Medicine','09:00',day);
  const planned=getScheduledDateTime(day,'09:00');
  const actual=new Date(Math.max(Date.parse(planned),Date.now())).toISOString();
  engine.record(state,med.id,'taken',actual);
  const completed=med.courseCompleted===true&&!med.archivedCompleted;
  engine.reconcile(state,new Date(Date.parse(actual)+7*86400000-1000).toISOString());
  const before=med.archivedCompleted===true;
  engine.reconcile(state,new Date(Date.parse(actual)+7*86400000).toISOString());
  const after=med.archivedCompleted===true;
  bridge.write(state);await bridge.checkpoint();
  return {completed,before,after,events:state.intakeLogs.length,archiveAt:med.archivedAt,expected:new Date(Date.parse(actual)+7*86400000).toISOString()};
 });
 expect(result.completed).toBe(true);expect(result.before).toBe(false);expect(result.after).toBe(true);
 expect(result.events).toBe(1);expect(result.archiveAt).toBe(result.expected);
 await page.getByRole('button',{name:'Выйти'}).click();await page.close();
 const reopened=await context.newPage();await reopened.goto('http://127.0.0.1:8765/tests/modular3-offline-access.html');
 await reopened.locator('#passphrase').fill('Archive-Synthetic-Secret-2026');
 await reopened.getByRole('button',{name:'Unlock offline'}).click();
 await reopened.getByRole('button',{name:'Архив'}).click();
 await expect(reopened.getByText(/Archive Test Medicine —/).first()).toBeVisible();
 const state=await reopened.evaluate(()=>MedControlOfflineEncryptedBridge.read());
 expect(state.medications[0].archivedCompleted).toBe(true);
 expect(state.intakeLogs).toHaveLength(1);
 expect(await reopened.evaluate(()=>localStorage.getItem('affixo_medcontrol_standard_v3'))).toBeNull();
 await context.close();
});
