'use strict';
const {test,expect}=require('@playwright/test');
test('encrypted functional offline prototype persists medicine and taken history across disconnected browser restart',async({browser})=>{
 const context=await browser.newContext({serviceWorkers:'allow',timezoneId:'Asia/Yerevan'});
 const page=await context.newPage();
 await page.goto('http://127.0.0.1:8765/tests/modular3-offline-access.html');
 await page.evaluate(async()=>{await navigator.serviceWorker.register('/tests/modular3-offline-sw.js',{scope:'/tests/'});await navigator.serviceWorker.ready;});
 await page.reload();
 await context.setOffline(true);
 await page.reload();
 await page.locator('#passphrase').fill('Functional-Offline-Secret-2026');
 await page.getByRole('button',{name:'Unlock offline'}).click();
 await page.getByRole('button',{name:'Ввод'}).click();
 await page.locator('input[name=name]').fill('Synthetic Offline Medicine');
 await page.locator('input[name=time]').fill('12:30');
 await page.getByRole('button',{name:'Добавить'}).click();
 await expect(page.getByText('Synthetic Offline Medicine')).toBeVisible();
 await page.getByRole('button',{name:'Приём препаратов'}).click();
 await page.getByRole('button',{name:'Принято'}).click();
 await page.getByRole('button',{name:'Отменить случайное нажатие'}).click();
 await page.getByRole('button',{name:'Табло'}).click();
 await expect(page.getByText('Препаратов: 1; записей приёма: 2')).toBeVisible();
 const status=await page.evaluate(()=>MedControlOfflineEncryptedBridge.read().intakeLogs[0]);
 expect(status.plannedAt).toBeTruthy();
 expect(status.actualAt).toBeTruthy();
 expect(['taken_early','taken_on_time','taken_late']).toContain(status.status);
 const history=await page.evaluate(()=>MedControlOfflineEncryptedBridge.read().intakeLogs);
 expect(history.map(e=>e.action)).toEqual(['taken','cancelled']);
 expect(history[1].status).toBe('cancelled');
 await page.getByRole('button',{name:'Архив'}).click();
 await expect(page.getByText(/Synthetic Offline Medicine —/)).toBeVisible();
 const raw=await page.evaluate(()=>({encrypted:localStorage.getItem('medcontrol_modular3_test_encrypted_state_v1'),plain:localStorage.getItem('affixo_medcontrol_standard_v3')}));
 expect(raw.plain).toBeNull();
 expect(raw.encrypted).not.toContain('Synthetic Offline Medicine');
 await page.getByRole('button',{name:'Выйти'}).click();
 await expect(page.getByText('Locked',{exact:true})).toBeVisible();
 await page.close();
 const reopened=await context.newPage();
 await reopened.goto('http://127.0.0.1:8765/tests/modular3-offline-access.html');
 await reopened.locator('#passphrase').fill('Wrong-Offline-Secret-2026');
 await reopened.getByRole('button',{name:'Unlock offline'}).click();
 await expect(reopened.getByText(/Access denied/)).toBeVisible();
 await reopened.locator('#passphrase').fill('Functional-Offline-Secret-2026');
 await reopened.getByRole('button',{name:'Unlock offline'}).click();
 await reopened.getByRole('button',{name:'Архив'}).click();
 await expect(reopened.getByText(/Synthetic Offline Medicine —/)).toBeVisible();
 await reopened.getByRole('button',{name:'Табло'}).click();
 await expect(reopened.getByText('Препаратов: 1; записей приёма: 1')).toBeVisible();
 await context.close();
});
