'use strict';
const {test,expect}=require('@playwright/test');
test('protected workspace: two slots, encrypted intake, offline unlock, four sections',async({browser})=>{
 const context=await browser.newContext({locale:'ru-RU',timezoneId:'Asia/Yerevan'});
 const page=await context.newPage();
 await page.clock.install({time:new Date('2026-10-14T05:31:00.000Z')});
 await page.goto('http://127.0.0.1:8765/modular3-protected.html?rehearsal=1');
 await page.locator('#password').fill('Synthetic-Local-Password-2026');
 await page.locator('#enroll').click();
 await expect(page.locator('#workspace')).toBeVisible();
 await page.locator('input[name="name"]').fill('Synthetic Course');
 await page.locator('input[name="date"]').fill('2026-10-14');
 for(const [hour,minute] of [['09','00'],['14','00']]){
  await page.getByLabel('Часы приёма').selectOption(hour);
  await page.getByLabel('Минуты приёма').selectOption(minute);
  await page.getByRole('button',{name:'Добавить время'}).click();
 }
 await page.locator('#screen form button').click();
 await expect(page.locator('#screen')).toContainText('09:00, 14:00');
 await page.locator('[data-tab="action"]').click();
 await expect(page.locator('#screen')).toContainText('09:00');
 await expect(page.locator('#screen')).toContainText('14:00');
 await page.getByRole('button',{name:'Принято 09:00'}).click();
 await expect(page.locator('#message')).toContainText('зашифрован');
 const snapshot=await page.evaluate(()=>({cipher:localStorage.getItem(MedControlModular3ProtectedSession.storageKey),legacy:localStorage.getItem('affixo_medcontrol_standard_v3')}));
 expect(snapshot.cipher).not.toContain('Synthetic Course');
 expect(snapshot.legacy).toBeNull();
 await page.locator('[data-tab="dashboard"]').click();
 await expect(page.locator('#screen')).toContainText('фактическое');
 await page.locator('[data-tab="archive"]').click();
 await expect(page.locator('#screen')).toContainText('фактическое');
 await page.locator('#lock').click();
 await expect(page.locator('#login')).toBeVisible();
 await page.reload();
 await context.setOffline(true);
 await page.locator('#password').fill('Synthetic-Local-Password-2026');
 await page.locator('#unlock').click();
 await expect(page.locator('#workspace')).toBeVisible();
 await page.locator('[data-tab="archive"]').click();
 await expect(page.locator('#screen')).toContainText('Synthetic Course');
 await expect(page.locator('#screen')).toContainText('фактическое');
 await context.close();
});
