'use strict';
const {test,expect}=require('@playwright/test');
const {setup,languages}=require('./functional-p1-fixture.cjs');
for(const {code}of languages)test('P1 all required hints, confirmation, weekday boundaries '+code,async({page},info)=>{
 const h=await setup(page,code);const {t,hint,surface,dialogs,medical}=h;
 await surface('empty-input');
 await hint(()=>page.locator('#create_contentValue').focus(),'Введите название препарата.');
 await page.locator('#create_name').fill('SYNTHETIC-P1-'+code);
 await hint(()=>page.locator('#create_contentUnit').focus(),'Введите количественное содержание препарата.');
 await page.locator('#create_contentValue').fill('1');
 await hint(()=>page.locator('#create_intakeQuantity').focus(),'Выберите единицу содержания.');
 await page.locator('#create_contentUnit').selectOption('other');
 await hint(()=>page.locator('#create_intakeQuantity').focus(),'Укажите другую единицу содержания.');
 await page.locator('#create_contentUnitOther').fill('SyntheticUnit');
 await hint(()=>page.locator('#create_intakeUnit').focus(),'Введите количество приёма.');
 await page.locator('#create_intakeQuantity').fill('1');
 await hint(()=>page.locator('#create_details').focus(),'Выберите единицу приёма.');
 await page.locator('#create_intakeUnit').selectOption('other');
 await hint(()=>page.locator('#create_details').focus(),'Укажите другую единицу приёма.');
 await page.locator('#create_intakeUnitOther').fill('SyntheticDose');
 await hint(()=>page.locator('#create_timeHour').focus(),'Заполните поле «Детали».');
 await page.locator('#create_details').fill('Synthetic data only');
 await hint(()=>page.locator('#create_startDate').focus(),'Добавьте хотя бы одно время.');
 await page.locator('#create_timeHour').selectOption('13');await page.locator('#create_timeMinute').selectOption('00');await page.locator('[data-med-sequence-action="add-time"]').click();
 await hint(()=>page.locator('[data-med-sequence-action="add-time"]').click(),'Это время уже добавлено.');
 await page.locator('#create_startDate').fill('');await hint(()=>page.locator('#create_endDate').focus(),'Дата начала не заполнена.');
 await page.locator('#create_startDate').fill('2026-11-24');await hint(()=>page.locator('#createMedicationButton').click(),'Дата окончания не заполнена.');
 await page.locator('#create_endDate').fill('2026-11-25');await page.locator('#createMedicationButton').click();await expect(page.locator('#medicationConfirmDialog')).toBeVisible();await surface('create-confirmation');
 await expect(page.locator('#medicationConfirmContent')).toContainText('SyntheticUnit');await expect(page.locator('#medicationConfirmContent')).toContainText('SyntheticDose');
 expect((await medical()).medications).toEqual([]);
 await page.locator('#medicationConfirmDialog button[onclick="proceedMedicationCreateConfirmation()"]').click();await expect(page.locator('#medicationSaveDialog')).toBeVisible();await surface('save-confirmation');
 await page.locator('#medicationSaveDialog button[onclick="backToMedicationConfirmation()"]').click();await page.locator('#medicationConfirmDialog button[onclick="cancelMedicationCreate()"]').click();
 await page.locator('#create_scheduleType').selectOption('weekdays');
 await hint(()=>page.locator('#create_startDate').focus(),'Отметьте хотя бы один день недели.');
 await page.locator('input[data-prefix="create_"][data-weekday="Mon"]').check();
 dialogs.length=0;await page.locator('#create_startDate').fill('2026-11-24');await expect.poll(()=>dialogs.length).toBe(1);
 expect(dialogs[0].message).toBe(t('Подсказка\n\nВыбранная дата начала не соответствует дням недели расписания. Ближайшая допустимая дата начала: ⟦0⟧.').replace('⟦0⟧',await page.evaluate(()=>formatDate('2026-11-30'))));
 dialogs.length=0;await page.locator('#create_endDate').fill('2026-11-25');await expect.poll(()=>dialogs.length).toBe(1);
 const dates=await page.evaluate(()=>[formatDate('2026-11-23'),formatDate('2026-11-30')]);
 expect(dialogs[0].message).toBe(t('Подсказка\n\nВыбранная дата окончания не соответствует дням недели расписания. Ближайшие допустимые даты: ⟦0⟧.').replace('⟦0⟧',dates.join(' '+t('или')+' ')));
 await page.locator('#create_scheduleType').selectOption('explicit_dates');
 await hint(()=>page.locator('[data-med-sequence-action="add-date"]').click(),'Сначала отметьте дату в календаре.');
 await page.locator('#create_datePicker').fill('2026-11-25');await page.locator('[data-med-sequence-action="add-date"]').click();
 await page.locator('#create_datePicker').fill('2026-11-25');await hint(()=>page.locator('[data-med-sequence-action="add-date"]').click(),'Эта дата уже добавлена.');
 await surface('explicit-date-form');expect((await medical()).medications).toEqual([]);
 await h.finish(info);
});
